const fs = require("fs");
const path = require("path");

const baseImg = "assets/programe/limbaj-receptiv/identifica-dupa-categorie/imagini";
const baseAudio = "assets/programe/limbaj-receptiv/identifica-dupa-categorie/audio";
const folders = [
  ["animale-domestice", "animale_domestice"],
  ["animale-salbatice", "animale_salbatice"],
  ["fructe", "fructe"],
  ["legume", "legume"],
  ["haine", "haine"],
];

const promptFiles = {
  animale_domestice: "arata un animal domestic.mp3",
  animale_salbatice: "arata un animal salbatic.mp3",
  fructe: "arata un fruct.mp3",
  legume: "arata o leguma.mp3",
  haine: "arata o haina.mp3",
};

let out = "";
out += "/** Metro static requires — generated by scripts/gen-receptive-identify-by-category-assets.js */\n";
out +=
  'export type IdentifyByCategoryId =\n  | "' +
  folders.map(([, id]) => id).join('"\n  | "') +
  '";\n\n';
out +=
  "export type IdentifyByCategoryItem = { id: string; categoryId: IdentifyByCategoryId; image: number };\n\n";

for (const [folder, cid] of folders) {
  const dir = path.join(__dirname, "..", baseImg, folder);
  const files = fs.readdirSync(dir).filter((x) => x.endsWith(".png")).sort();
  out += `const POOL_${cid.toUpperCase()}: IdentifyByCategoryItem[] = [\n`;
  for (const file of files) {
    const baseName = file.replace(/\.png$/, "");
    const reqPath = "../../../" + path.join(baseImg, folder, file).replace(/\\/g, "/");
    out += `  { id: "${baseName}", categoryId: "${cid}", image: require("${reqPath}") },\n`;
  }
  out += "];\n\n";
}

out += "export const IDENTIFY_BY_CATEGORY_POOLS: Record<IdentifyByCategoryId, IdentifyByCategoryItem[]> = {\n";
for (const [, cid] of folders) {
  out += `  ${cid}: POOL_${cid.toUpperCase()},\n`;
}
out += "};\n\n";
out += "export function getIdentifyByCategoryPool(categoryId: IdentifyByCategoryId): IdentifyByCategoryItem[] {\n";
out += "  return IDENTIFY_BY_CATEGORY_POOLS[categoryId] ?? [];\n";
out += "}\n\n";

out += "const PROMPT_AUDIO: Record<IdentifyByCategoryId, number> = {\n";
for (const [, cid] of folders) {
  const mp3 = promptFiles[cid];
  const reqPath = "../../../" + path.join(baseAudio, mp3).replace(/\\/g, "/");
  out += `  ${cid}: require("${reqPath}"),\n`;
}
out += "};\n\n";
out += "export function getIdentifyByCategoryPromptAudio(categoryId: IdentifyByCategoryId): number {\n";
out += "  return PROMPT_AUDIO[categoryId];\n";
out += "}\n\n";
out += "export function isIdentifyByCategoryId(s: string): s is IdentifyByCategoryId {\n";
out += "  return s in IDENTIFY_BY_CATEGORY_POOLS;\n";
out += "}\n";

const outPath = path.join(
  __dirname,
  "..",
  "src/features/receptive-language/identifyByCategoryAssets.ts"
);
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, out);
console.log("Wrote", outPath);
